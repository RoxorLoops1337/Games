const PREFIX = 'dtb-shell-';
const CACHE = PREFIX + VERSION;
const RUNTIME = 'dtb-runtime-v1';
const BASE = new URL('./', self.location).pathname;   // /drop_the_bass/
const abs = (p) => new URL(p, self.location).href;

self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await Promise.all(PRECACHE.map((f) => c.add(new Request(abs(f), { cache: 'reload' }))));
    // first install has no old worker to wait for
    if (!self.registration.active) self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if ((k.startsWith(PREFIX) && k !== CACHE) || (k.startsWith('dtb-runtime-') && k !== RUNTIME)) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (e) => {
  if (e.data === 'SKIP_WAITING' || (e.data && e.data.type === 'SKIP_WAITING')) self.skipWaiting();
  if (e.data === 'GET_VERSION' && e.source) e.source.postMessage({ type: 'VERSION', version: VERSION });
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return;            // never cache the leaderboards, saves or stats
  if (!url.pathname.startsWith(BASE)) return;
  e.respondWith(handle(req, url));
});

async function handle(req, url) {
  const shell = await caches.open(CACHE);
  if (req.mode === 'navigate') {
    const hit = await shell.match(abs('index.html'), { ignoreSearch: true });
    if (hit) return hit;
    try { return await fetch(req); } catch (err) { return offlinePage(); }
  }
  const rel = url.pathname.slice(BASE.length);
  if (PRECACHE.includes(rel)) {
    const hit = await shell.match(abs(rel), { ignoreSearch: true });
    if (hit) return hit;
  }
  // stale-while-revalidate for the rest
  const rt = await caches.open(RUNTIME);
  const cached = await rt.match(req);
  const net = fetch(req).then((res) => { if (res && res.ok && res.type === 'basic') rt.put(req, res.clone()); return res; }).catch(() => null);
  if (cached) { net.catch(() => {}); return cached; }
  const res = await net;
  return res || (req.destination === 'document' ? offlinePage() : new Response('', { status: 504, statusText: 'offline' }));
}

function offlinePage() {
  return new Response('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Offline</title><body style="font:22px sans-serif;background:#fbf6e6;color:#2b2733;text-align:center;padding:20vh 24px"><b>Drop the Bass</b><p>You are offline and the game is not saved on this device yet. Reconnect once and it will work offline next time.</p>', { status: 200, headers: { 'content-type': 'text/html; charset=utf-8' } });
}
