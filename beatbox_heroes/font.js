  const cache = {};
  function glyph(ch) {
    ch = String(ch).toUpperCase();
    if (cache[ch]) return cache[ch];
    return (cache[ch] = G[ch] || G['?']);
  }
  const width = (str, scale, spacing) => { scale = scale || 1; spacing = spacing === undefined ? 1 : spacing; return str.length ? str.length * (5 * scale + spacing * scale) - spacing * scale : 0; };
  function draw(pix, str, x, y, color, o) {
    o = o || {}; const sc = o.scale || 1, sp = o.spacing === undefined ? 1 : o.spacing;
    const paint = (ox, oy, col) => {
      let cx = x + ox;
      for (const ch of String(str)) {
        const g = glyph(ch);
        for (let j = 0; j < 7; j++) for (let i = 0; i < 5; i++) if (g[j][i] === '#') pix.rect(cx + i * sc, y + oy + j * sc, sc, sc, col);
        cx += (5 + sp) * sc;
      }
    };
    if (o.outline) for (const [ox, oy] of [[-sc, 0], [sc, 0], [0, -sc], [0, sc], [-sc, -sc], [sc, sc], [-sc, sc], [sc, -sc]]) paint(ox, oy, o.outline);
    if (o.shadow) paint(sc, sc * 2 - (o.outline ? 0 : 0), o.shadow);
    paint(0, 0, color);
    return pix;
  }
  function text(str, o) {
    o = o || {}; const sc = o.scale || 1, pad = (o.outline || o.shadow ? sc * 2 : 0) + (o.pad || 0);
    const p = new Pix(width(String(str), sc, o.spacing) + pad * 2 + (o.shadow ? sc : 0), 7 * sc + pad * 2 + (o.shadow ? sc * 2 : 0));
    return draw(p, str, pad, pad, o.color || '#ffffff', o);
  }
  BBH.Font = { glyph, width, draw, text, GLYPHS: G };
