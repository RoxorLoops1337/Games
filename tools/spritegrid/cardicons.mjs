/**
 * A seed-orb. A sphere is the one shape a formula draws better than a hand
 * does: the band across the middle is the seam the shell opens on, and the
 * light is thrown from the upper left like everything else in the set.
 */
const orbArt = () => {
  const R = 9.4, cx = 9.5, cy = 9.5;
  const rows = [];
  for (let y = 0; y < 20; y++) {
    let row = '';
    for (let x = 0; x < 20; x++) {
      const dx = x + .5 - cx, dy = y + .5 - cy, d = Math.hypot(dx, dy);
      if (d > R) { row += '.'; continue; }
      if (d > R - 1.3) { row += 'K'; continue; }
      if (y === 9) { row += 'K'; continue; }
      if (y === 10) { row += 'a'; continue; }
      // Shade off the sphere's own normal, not off a straight diagonal: a
      // linear ramp across a circle bands into stripes, which is what the
      // first pass at these looked like.
      const nx = dx / R, ny = dy / R;
      const nz = Math.sqrt(Math.max(0, 1 - nx * nx - ny * ny));
      const L = 1 / Math.sqrt(.5 * .5 + .5 * .5 + .8 * .8);
      const l = (nx * -.5 + ny * -.5 + nz * .8) * L;
      row += l > .93 ? 'h' : l > .74 ? 'b' : l > .42 ? 'm' : 'd';
    }
    rows.push(row);
  }
  return rows.join('\n');
};

