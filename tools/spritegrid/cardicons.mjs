// ---------------------------------------------------------------- write out
const built = [];
for (const [id, [pal, art]] of Object.entries(ICONS)) {
  const rows = art.trim().split('\n').map((r) => r.replace(/\r/g, ''));
  const used = new Set();
  for (const r of rows) for (const ch of r) if (ch !== '.') used.add(ch);
  const palette = {};
  for (const ch of [...used].sort()) {
    if (!P[pal][ch]) throw new Error(`${id}: palette "${pal}" has no colour for "${ch}"`);
    palette[ch] = P[pal][ch];
  }
  const sp = { id, name: id, w: 20, h: 20, palette, rows };
  validate(sp, id);
  built.push(sp);
}

mkdirSync(OUT, { recursive: true });
for (const sp of built) {
  writeFileSync(join(OUT, `${sp.id}.json`), JSON.stringify(sp, null, 2) + '\n');
}
console.log(`wrote ${built.length} card icons → emberkin/art/cards/`);

if (process.argv.includes('--sheet')) {
  const out = process.argv[process.argv.indexOf('--sheet') + 1] || '/tmp/cardicons.png';
  const img = sheet(built, 6, 8);
  writeFileSync(out, encodePNG(img.data, img.W, img.H));
  console.log(`contact sheet → ${out}`);
}
