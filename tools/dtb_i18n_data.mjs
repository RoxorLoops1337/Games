// Drop the Bass: data translation tool.
//   node tools/dtb_i18n_data.mjs --extract   write drop_the_bass/js/lang/en_data.js (path -> English) from the live data tables
//   node tools/dtb_i18n_data.mjs --check     verify drop_the_bass/js/lang/{da,nl,de}_data.js against en_data.js (exit 1 on errors)
//   node tools/dtb_i18n_data.mjs --stub      create/complete da/nl/de files: keep existing translations, fill missing keys with English
// Checks: missing keys, extra keys, {placeholder} and {markup} consistency, em dashes, length of canvas fields (names: warn > 26, error > 30).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LANG_DIR = path.join(ROOT, 'drop_the_bass', 'js', 'lang');
export const CODES = ['da', 'nl', 'de'];
export const NAME_WARN = 26, NAME_MAX = 30;

export function serialize(map, header) {
  const keys = Object.keys(map).sort();
  return header + 'export default {\n' + keys.map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(map[k]) + ',').join('\n') + '\n};\n';
}
const EN_HEADER = '// Drop the Bass: English text of the data tables (path -> string). GENERATED by `node tools/dtb_i18n_data.mjs --extract`, do not edit.\n// Translations: js/lang/<da|nl|de>_data.js with the same keys. Keep {placeholders} and no em dashes.\n';
const LANG_HEADER = (c) => '// Drop the Bass: ' + c + ' translation of the data tables. Keys come from en_data.js (tools/dtb_i18n_data.mjs --check). Missing keys fall back to English.\n';

export async function liveEnglish() {
  const m = await import('../drop_the_bass/js/i18n_data.js');
  return m.englishMap();
}
export async function readDict(file) {
  if (!fs.existsSync(file)) return null;
  const m = await import(pathToFileURL(file).href + '?t=' + Date.now());
  return m.default;
}
const marks = (s) => (String(s).match(/\{[^}]*\}/g) || []).sort().join('|');
const isName = (k) => /\.name$/.test(k) || /^FAME_TITLES\./.test(k);

export function checkDict(code, en, dict) {
  const errors = [], warns = [];
  if (!dict) return { errors: [code + ': file js/lang/' + code + '_data.js is missing'], warns };
  for (const k of Object.keys(en)) {
    if (!(k in dict)) { errors.push(code + ': missing ' + k); continue; }
    const v = dict[k];
    if (typeof v !== 'string' || v === '') { errors.push(code + ': empty or non-string ' + k); continue; }
    if (marks(en[k]) !== marks(v)) errors.push(code + ': placeholders differ in ' + k + ' (' + marks(en[k]) + ' vs ' + marks(v) + ')');
    if (v.includes('\u2014')) errors.push(code + ': em dash in ' + k);
    if (isName(k)) { if (v.length > NAME_MAX) errors.push(code + ': name too long (' + v.length + ') ' + k); else if (v.length > NAME_WARN) warns.push(code + ': name long (' + v.length + ') ' + k); }
  }
  for (const k of Object.keys(dict)) if (!(k in en)) errors.push(code + ': extra key ' + k);
  return { errors, warns };
}

async function main() {
  const arg = process.argv[2];
  const en = await liveEnglish();
  const enFile = path.join(LANG_DIR, 'en_data.js');
  if (arg === '--extract') {
    fs.mkdirSync(LANG_DIR, { recursive: true });
    fs.writeFileSync(enFile, serialize(en, EN_HEADER));
    console.log('en_data.js: ' + Object.keys(en).length + ' strings');
  } else if (arg === '--stub') {
    for (const c of CODES) {
      const f = path.join(LANG_DIR, c + '_data.js');
      const cur = (await readDict(f)) || {};
      const out = {}; let added = 0;
      for (const k of Object.keys(en)) { if (typeof cur[k] === 'string' && cur[k] !== '') out[k] = cur[k]; else { out[k] = en[k]; added++; } }
      fs.writeFileSync(f, serialize(out, LANG_HEADER(c)));
      console.log(c + '_data.js: ' + Object.keys(out).length + ' keys, ' + added + ' filled with English');
    }
  } else if (arg === '--check') {
    let bad = 0;
    const fileEn = await readDict(enFile);
    if (!fileEn || JSON.stringify(fileEn) !== JSON.stringify(Object.fromEntries(Object.keys(en).sort().map((k) => [k, en[k]])))) { console.log('en_data.js is out of date: run --extract'); bad++; }
    for (const c of CODES) {
      const r = checkDict(c, en, await readDict(path.join(LANG_DIR, c + '_data.js')));
      for (const w of r.warns) console.log('warn  ' + w);
      for (const e of r.errors) console.log('ERROR ' + e);
      bad += r.errors.length;
      console.log(c + ': ' + r.errors.length + ' errors, ' + r.warns.length + ' warnings');
    }
    process.exit(bad ? 1 : 0);
  } else { console.log('usage: node tools/dtb_i18n_data.mjs --extract | --check | --stub'); process.exit(2); }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
