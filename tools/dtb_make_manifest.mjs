// Builds the Drop the Bass service worker precache list and cache version, and writes them into the marked block of
// drop_the_bass/sw.js plus drop_the_bass/precache.json. The version is a hash of every precached file, so any change to
// the app shell changes sw.js, which is what makes browsers install the new worker.
// Run: node tools/dtb_make_manifest.mjs  (build.js runs it before copying; tests/drop_the_bass_pwa.test.mjs checks it is current)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'drop_the_bass');
const START = '/* PRECACHE:BEGIN (generated by tools/dtb_make_manifest.mjs, do not edit) */';
const END = '/* PRECACHE:END */';

const walk = (d, rel = '') => fs.readdirSync(path.join(d, rel), { withFileTypes: true }).flatMap((e) => {
  const r = rel ? rel + '/' + e.name : e.name;
  return e.isDirectory() ? walk(d, r) : [r];
});

export function shellFiles() {
  const all = [...walk(DIR, 'js'), ...walk(DIR, 'fonts'), ...walk(DIR, 'icons')].filter((f) => /\.(js|woff2|png)$/.test(f));
  const top = ['index.html', 'ui.css', 'ui_doodle.css', 'manifest.webmanifest'];
  return [...top, ...all].filter((f) => fs.existsSync(path.join(DIR, f))).sort();
}

export function compute() {
  const files = shellFiles();
  const h = crypto.createHash('sha256');
  for (const f of files) { h.update(f + '\0'); h.update(fs.readFileSync(path.join(DIR, f))); h.update('\0'); }
  return { version: h.digest('hex').slice(0, 12), files };
}

export function blockFor(m) {
  return START + '\nconst VERSION = ' + JSON.stringify(m.version) + ';\nconst PRECACHE = ' + JSON.stringify(m.files, null, 1).replace(/\n\s*/g, ' ').replace('[ ', '[\n  ').replace(/", "/g, '",\n  "') + ';\n' + END;
}

export function currentBlock() {
  const src = fs.readFileSync(path.join(DIR, 'sw.js'), 'utf8');
  const a = src.indexOf(START), b = src.indexOf(END);
  return { src, a, b, block: a >= 0 && b > a ? src.slice(a, b + END.length) : null };
}

export function write() {
  const m = compute();
  const cur = currentBlock();
  if (cur.block === null) throw new Error('sw.js has no PRECACHE block');
  const next = cur.src.slice(0, cur.a) + blockFor(m) + cur.src.slice(cur.b + END.length);
  if (next !== cur.src) fs.writeFileSync(path.join(DIR, 'sw.js'), next);
  const pj = JSON.stringify({ version: m.version, files: m.files }, null, 1) + '\n';
  const pp = path.join(DIR, 'precache.json');
  if (!fs.existsSync(pp) || fs.readFileSync(pp, 'utf8') !== pj) fs.writeFileSync(pp, pj);
  return m;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const m = write();
  console.log('drop_the_bass precache: ' + m.files.length + ' files, version ' + m.version);
}
