/* ============================================================================
   build.mjs — cut the two typefaces and embed them in the game.

     node tools/beastfont/build.mjs            # rebuild + rewrite the @font-face
     node tools/beastfont/build.mjs --check    # fail if what is embedded is stale
     node tools/beastfont/build.mjs --specimen # also write a page to look at

   The fonts are WOFF, base64'd straight into birds_and_beasts/index.html. That
   file is one self-contained document by design — no external resources — and a
   web font is the one thing that would quietly break that rule, so it goes in
   the same way everything else does: inline.

   Two families, three files:
     BEASTCUT  — the display face. One weight, already black; declared across
                 the whole 100-900 range so no browser ever synthesises a bold
                 on top of a face that is already as heavy as it gets.
     BEAKWORK  — the text face, regular + bold, cut from the same skeleton with
                 a heavier metric bundle rather than smeared by the renderer.
   ========================================================================== */
