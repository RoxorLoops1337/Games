/* The three faces are already in this page as data: URIs inside @font-face.
   Rather than ship a second copy for the download links, pull them back out of
   the stylesheet and hand them over as blobs. */
(function(){
  var css = document.styleSheets[0], seen = {}, out = document.getElementById('dl');
  for (var i = 0; i < css.cssRules.length; i++) {
    var r = css.cssRules[i];
    if (!(r instanceof CSSFontFaceRule)) continue;
    var fam = r.style.getPropertyValue('font-family').replace(/['"]/g, '').trim();
    var wt = (r.style.getPropertyValue('font-weight') || '400').trim();
    // Beastcut is declared across 100-900 (it has one weight and is already
    // black), so the file name comes from the family, not from the number.
    var name = fam === 'Beastcut' ? 'Beastcut.woff'
      : 'Beakwork-' + (/^4/.test(wt) ? 'Regular' : 'Bold') + '.woff';
    if (seen[name]) continue;
    seen[name] = 1;
    var m = /base64,([A-Za-z0-9+/=]+)/.exec(r.style.getPropertyValue('src'));
    if (!m) continue;
    var bin = atob(m[1]), buf = new Uint8Array(bin.length);
    for (var k = 0; k < bin.length; k++) buf[k] = bin.charCodeAt(k);
    var a = document.createElement('a');
    a.href = URL.createObjectURL(new Blob([buf], { type: 'font/woff' }));
    a.download = name;
    a.textContent = name.replace('.woff', '') + ' — ' + Math.round(buf.length / 102.4) / 10 + 'kB';
    out.appendChild(a);
  }
})();
