/* ------------------------------------------------------------- the faces --- */

// BEASTCUT — condensed, black, chiselled. The superellipse at 0.64 is what
// flattens every bowl; the chamfer knocks the corners off the stems so the
// letters read as cut plate rather than as extruded type.
export const BEASTCUT = {
  cap: 720, asc: 780, desc: -190,
  st: 150, th: 124, e: 0.64, ch: 42, ov: 12,
  wf: 0.94, side: 30, N: 12,
  cA: 46, sT: 0.575, sB: 0.595, sA0: -14,
};
// Its small caps: shorter, wider, and proportionally FATTER, so a mixed-case
// title keeps one even colour instead of going pale where the lowercase is.
export const BEASTCUT_SC = {
  ...BEASTCUT, cap: 540, st: 128, th: 108, ch: 34, ov: 10, wf: 1.06, side: 28,
};

// BEAKWORK — the text face. Tall x-height, open apertures, low contrast, and
// terminals that stop dead: it has to survive a 10px uppercase label with 2.6px
// of tracking, which is most of this game's chrome.
export const BEAKWORK = {
  cap: 700, xh: 516, asc: 742, desc: -206,
  st: 86, th: 79, e: 0.80, ch: 0, ov: 11,
  wf: 1.0, side: 48, N: 14,
  cA: 38, cAl: 34, sT: 0.585, sB: 0.61, sA0: -12,
};
export const BEAKWORK_BOLD = {
  ...BEAKWORK, st: 142, th: 126, wf: 1.035, side: 44, ov: 12,
};

/* ------------------------------------------------------------- assembly --- */
function notdef(adv, cap) {
  const m = Math.round(cap * 0.10);
  return glyph('.notdef', 0, adv,
    [[[m, 0], [adv - m, 0], [adv - m, cap], [m, cap]]],
    [[[m * 2, m * 2], [adv - m * 2, m * 2], [adv - m * 2, cap - m * 2], [m * 2, cap - m * 2]]]);
}

function makeFont(map, spec) {
  const chars = Object.keys(map).sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
  const space = map[' '];
  const glyphs = [notdef(Math.round(space.adv * 1.4), spec.capHeight)];
  for (const ch of chars) {
    const gl = map[ch];
    glyphs.push(glyph(ch, ch.codePointAt(0), gl.adv, gl.pos, gl.cut));
  }
  glyphs.push(glyph('nbsp', 0x00a0, space.adv, [], []));   // never a visible gap
  return buildFont({ ...spec, unitsPerEm: EM, glyphs });
}

function names(family, style, ver) {
  const full = style === 'Regular' ? family : `${family} ${style}`;
  return [
    [0, 'Drawn for The Birds & The Beasts. Generated by tools/beastfont.'],
    [1, family], [2, style], [3, `${full}:beastfont`], [4, full],
    [5, `Version ${ver}`], [6, full.replace(/[^A-Za-z0-9]/g, '')],
    [8, 'The Birds & The Beasts'], [11, 'https://games-71g.pages.dev/birds_and_beasts/'],
  ];
}

export function cutFonts() {
  const display = { ...buildFace(BEASTCUT), ...smallCaps(BEASTCUT_SC) };
  const text = buildFace(BEAKWORK);
  const bold = buildFace(BEAKWORK_BOLD);

  return [
    {
      id: 'beastcut', family: 'Beastcut', style: 'Regular', weight: 400,
      font: makeFont(display, {
        ascender: 800, descender: -220, lineGap: 0,
        capHeight: BEASTCUT.cap, xHeight: BEASTCUT_SC.cap, weight: 400,
        names: names('Beastcut', 'Regular', '1.000'),
      }),
    },
    {
      id: 'beakwork', family: 'Beakwork', style: 'Regular', weight: 400,
      font: makeFont(text, {
        ascender: 800, descender: -220, lineGap: 0,
        capHeight: BEAKWORK.cap, xHeight: BEAKWORK.xh, weight: 400,
        names: names('Beakwork', 'Regular', '1.000'),
      }),
    },
    {
      id: 'beakwork-bold', family: 'Beakwork', style: 'Bold', weight: 700,
      font: makeFont(bold, {
        ascender: 800, descender: -220, lineGap: 0,
        capHeight: BEAKWORK_BOLD.cap, xHeight: BEAKWORK_BOLD.xh, weight: 700,
        names: names('Beakwork', 'Bold', '1.000'),
      }),
    },
  ];
}

/* --------------------------------------------------------------- embed --- */
const BEGIN = '/* BEASTFONT:BEGIN — generated by tools/beastfont/build.mjs, do not hand-edit */';
const END = '/* BEASTFONT:END */';

export function faceBlock(cut) {
  const face = (c, family, weight, style) =>
    `  @font-face{ font-family:'${family}'; font-style:${style}; font-weight:${weight};\n` +
    `    src:url(data:font/woff;base64,${c.font.woff.toString('base64')}) format('woff'); font-display:block; }`;
  const [d, r, b] = cut;
  return [
    BEGIN,
    face(d, 'Beastcut', '100 900', 'normal'),
    face(r, 'Beakwork', '400', 'normal'),
    face(b, 'Beakwork', '700 900', 'normal'),
    END,
  ].join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const cut = cutFonts();
  const block = faceBlock(cut);

  // The game keeps its own hand-written CSS around the block, so it is spliced.
  // The specimen page is generated whole — it exists only to show the faces off
  // and to hand the .woff files out, so there is nothing in it to preserve.
  const src = readFileSync(GAME, 'utf8');
  const i = src.indexOf(BEGIN), j = src.indexOf(END);
  if (i < 0 || j < 0) {
    console.error('beastfont: no BEASTFONT:BEGIN/END markers in birds_and_beasts/index.html');
    process.exit(1);
  }
  const page = specimen(block);

  if (check) {
    let stale = false;
    if (src.slice(i, j + END.length) !== block) { console.error('beastfont: index.html is STALE'); stale = true; }
    if (readFileSync(SPEC, 'utf8') !== page) { console.error('beastfont: fonts.html is STALE'); stale = true; }
    if (stale) { console.error('beastfont: run `node tools/beastfont/build.mjs`'); process.exit(1); }
    console.log('beastfont: embedded fonts match source ✓');
  } else {
    writeFileSync(GAME, src.slice(0, i) + block + src.slice(j + END.length));
    writeFileSync(SPEC, page);
    const kb = (n) => (n / 1024).toFixed(1) + 'kB';
    for (const c of cut) console.log(`  ${c.family} ${c.style}: ${kb(c.font.ttf.length)} ttf → ${kb(c.font.woff.length)} woff`);
    console.log(`beastfont: embedded ${kb(block.length)} into the game and into fonts.html`);
  }

  if (args.includes('--woff')) {
    const out = join(HERE, 'out');
    mkdirSync(out, { recursive: true });
    for (const c of cut) writeFileSync(join(out, c.id + '.woff'), c.font.woff);
    console.log('beastfont: wrote tools/beastfont/out/*.woff');
  }
}

